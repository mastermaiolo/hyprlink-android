fun getAppStrings(lang: AppLanguage): AppStrings {
    return when (lang) {
        AppLanguage.PT_BR -> STRINGS_PT_BR
        AppLanguage.PT_PT -> STRINGS_PT_PT
        AppLanguage.EN_UK -> STRINGS_EN_UK
        AppLanguage.ES_ES -> STRINGS_ES_ES
        AppLanguage.ZH_CN -> STRINGS_ZH_CN
        AppLanguage.SYSTEM -> STRINGS_PT_BR
    }
}

